fn instruction_source_path_uris(sources: &[LegacyAppPathString]) -> Vec<PathUri> {
    sources
        .iter()
        .filter_map(|source| {
            source.to_inferred_path_uri().or_else(|| {
                tracing::warn!(
                    path = source.as_str(),
                    "ignoring invalid instruction source path from app-server"
                );
                None
            })
        })
        .collect()
}

